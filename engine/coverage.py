    id: str
    title: str
    status: str                 # BUILT / PARTIAL / MISSING (what the engine does today)
    impact: str                 # BLOCKER / GAMEPLAY / POLISH when it is not built
    step: str = ""              # the Step that builds it
    note: str = ""


