"""Map coverage report (phase K0): what stands between each original map and full playability.

    python -m engine coverage [GAME_DIR] [--ticks N] [--csv PATH] [--docs PATH]

For every campaign map the data is scanned for the features the engine needs (script kinds reachable from an active trigger, usable structures,
quest items, caster / ranged units, the spells of units and items, music zones), each feature carries the engine's status (`built`, `partial` = a
documented counted no-op, `missing`) and an impact (`blocker` = the mission cannot be completed as designed, `gameplay`, `polish`), and a short
headless smoke run (the map script and the AI, no player) shows what the engine itself reports.  Output: `out/coverage.csv` (map x feature) and the
generated block of `docs/coverage.md` (per map: playable now or its blockers; per feature: how many maps it unblocks; the proposed step order).

The statuses are data kept here (`FEATURES`, `STEPS`): a K step that builds a feature flips its status in the same change (the close-out rule in
CLAUDE.md).  Trigger kinds are not listed by hand: `trigger_status` asks the trigger code itself, so a new kind shows up as built.
Layer 5 tooling: reads `engine.world`, `engine.sim`, the core loaders; writes only the two output files.
"""

