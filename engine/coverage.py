TRIGGER_GROUP = {"check": "checks", "instant": "instants", "group": "group commands"}


# --- trigger kinds: ask the trigger code ---------------------------------------------------------------------------------------------------------

def trigger_status(what, kind):
    """BUILT or MISSING for a check / instant / group command kind, from the trigger code itself: a kind with no branch raises NotImplementedError
    (checks, groups: strict script) or records "Bad instant" (instants); a built branch fed empty arguments raises anything else or nothing."""
    from engine.sim import triggers as T
    script = T.Script(strict=True)
    world = types.SimpleNamespace(tick=0, events=[], units={}, players={}, items={})
    try:
        if what == "check":
            T.eval_check(world, script, T.Compiled(0, kind, "", [0] * S.ARGS))
        elif what == "instant":
            script.instants.append(T.Compiled(0, kind, "", [0] * S.ARGS))
            T.run_instant(world, script, 0)
            return MISSING if script.errors else BUILT
        else:
            T._set_group_order(world, script, None, kind, [0] * S.ARGS)
    except NotImplementedError:
        return BUILT if what == "instant" else MISSING      # an instant 6 with the probe's empty group command: the kind itself has a branch
    except Exception:           # an argument the probe left empty: the kind has a branch
        pass
    return BUILT


def script_feature(what, kind):
    """The Feature of a script kind: `check.N` / `instant.N` / `group.N`, named from the editor tables."""
    from engine.sim import triggers as T
    fid = "%s.%d" % (what, kind)
    title = "%s %d: %s" % (what, kind, T._NAMES[what].get(kind, "unnamed"))
    if (what, kind) in PARTIAL_KINDS:
        note, impact, step = PARTIAL_KINDS[(what, kind)]
        return Feature(fid, title, PARTIAL, impact, step, note)
    status = trigger_status(what, kind)
    return Feature(fid, title, status, BLOCKER if status == MISSING else POLISH, "", "")


# --- per-map scan ---------------------------------------------------------------------------------------------------------------------------------

def reachable_records(scenario):
    """`(what, record)` for every check and instant an active trigger names (a record no trigger reaches never runs)."""
    checks = {r.id: r for r in scenario.checks}
    instants = {r.id: r for r in scenario.instants}
    for t in scenario.triggers:
        if not t.active:
            continue
        for a, b in t.pairs:
            for x in (a, b):
                if x in checks:
                    yield "check", checks[x]
        for i in t.instants:
            if i in instants:
                yield "instant", instants[i]


def reachable_kinds(scenario):
    """`{("check" | "instant" | "group", kind): count}` over `reachable_records`.  Variable references (8000-9999) and unit names (>= 11001) are
    reported as `varref` / `unitname` (the exe never writes the table: triggers.md 2.3)."""
    out = Counter()
    for what, r in reachable_records(scenario):
        if r.type >= S.CONSTANT:
            continue
        out[(what, r.type)] += 1
        if what == "instant" and r.type == 6 and r.values:
            out[("group", r.values[0])] += 1
        for k, v in r.args():
            if S.VAR_LOW <= v <= S.VAR_HIGH and k in S.OBJECT_KINDS:
                out[("varref", 0)] += 1
            if k == S.K_UNIT and v >= S.NAMED_BASE:
                out[("unitname", 0)] += 1
    return out


def scripted_structures(m, reg):
    """Usable structures a script reads or sets: the building argument of a reachable check 21 (health) or instant 26 (set health).  A switch puzzle
    is such a map: the script watches the switches' state, so a mission that cannot use them cannot be completed."""
    usable = {s.uid for s in m.structures if reg.get(s.type, {}).get("Usable")}
    return {v for what, r in reachable_records(m.scenario) if r.type == (21 if what == "check" else 26)
            for k, v in r.args() if k == S.K_BUILDING and v in usable}


def _items_of(scenario, kinds, types_):
    """The special-item codes (argument kind 8 + 0xe18) of the reachable records of the given types."""
    codes = set()
    for r in list(scenario.checks) + list(scenario.instants):
        if r.type in types_:
            codes.update((v + S.ITEM_BASE) & 0xFFFF for k, v in r.args() if k == S.K_ITEM)
    return codes


def quest_items_on_map(m):
    """Item codes a check waits for that a monster carries or a sack holds at map start and that no instant hands out."""
    sc = m.scenario
    needed = _items_of(sc, None, (12, 16, 17))
    given = _items_of(sc, None, (11, 12, 28))
    party = {u.group for u in m.units if u.group and u.owner == 1}
    placed = {mem.code & 0xFFFF for i, g in enumerate(m.item_groups, 1) if i not in party for mem in g.members}
    return (needed & placed) - given


def spell_sources(world, m, assets):
    """`{spell number: sources}` of the map: unit types with a book or slot, items (castSpell / teachSpell modifiers, equipment strings)."""
    from engine.sim import spells as sp
    from allods2.formats.itemdefs import STAT_CAST, STAT_TEACH
    table = assets.items()
    out = Counter()
    for u in world.units.values():
        if u.owner == 1 and u.stats is not None and u.stats.kind == "human" and u.stats.name.startswith(("Start", "Fighter_Hero", "Mage_Hero")):
            continue
        mask = sp.known_mask(u)
        for n in range(1, 30):
            if mask >> n & 1:
                out[n] += 1
        for mods in u.carried_mods or ():
            for kind, a, _b in mods:
                if kind in (STAT_CAST, STAT_TEACH):
                    out[a & 0xFF] += 1
    for it in world.items.values():
        for mods in it.mods or ():
            for kind, a, _b in mods:
                if kind in (STAT_CAST, STAT_TEACH):
                    out[a & 0xFF] += 1
    seen = set()
    for u in world.units.values():
        t = u.stats
        if t is None or t.name in seen:
            continue
        seen.add(t.name)
        for text in t.equipment:
            for name in re.findall(r"castSpell=(\w+)", text or ""):
                n = table.spell_id(name)
                if n:
                    out[n] += 1
    return out


def scan(world, m, assets):
    """`{feature id: count}` for one map (built world, parsed map)."""
    from engine.sim.combat import combat_stats
    f = Counter()
    for (what, kind), n in reachable_kinds(m.scenario).items():
        f["%s.%d" % (what, kind) if what in ("check", "instant", "group") else what] += n
    reg = assets.structures_reg()
    sc = m.scenario
    live = {}                       # signpost uid -> the type of the instant it runs (the runtime index must be > 0: map.md part 6)
    for p in m.section11[2]:
        if p.enabled and S.runtime_instant_index(sc.instants, p.instant) > 0 and p.instant < len(sc.instants):
            live[p.uid] = sc.instants[p.instant].type
    for s in m.structures:
        rec = reg.get(s.type, {})
        if not rec.get("Usable"):
            continue
        for prefix, kind in USE_KINDS:
            if rec.get("DescText", "").startswith(prefix):
                if kind != "pointer":
                    f["use." + kind] += 1
                elif s.uid in live:
                    f["use.pointer" if live[s.uid] == 2 else "use.pointer_script"] += 1
                break
    f["use.scripted"] = len(scripted_structures(m, reg))
    f["item.quest_pickup"] = len(quest_items_on_map(m))
    for u in world.units.values():
        t = u.stats
        if t is None or u.owner == 1:
            continue
        from engine.sim import spells as sp
        if sp.known_mask(u):
            f["unit.caster"] += 1
        elif combat_stats(world, u).range > 1:
            f["unit.ranged"] += 1
        mt = t.get("movement_type", 1)
        if mt == 3:
            f["unit.flyer"] += 1
        elif mt == 2:
            f["unit.ghost"] += 1
    spells = spell_sources(world, m, assets)
    for n, c in spells.items():
        f["spell.%d" % n] += c
        if n in STATUS_SPELLS:
            f["spell.status"] += c
    default, zones = m.music
    f["music.zones"] = len(zones) + (1 if default is not None and default.themes[0] >= 0 else 0)
    return +f


def smoke(name, install, ticks):
    """Build the map as `play` does and run `ticks` with the script and the AI and no player.  Returns the engine's own reports."""
    from engine.session import build_game
    from engine.sim import Simulation, triggers
    logs = []

    class Catch(logging.Handler):
        def emit(self, r):
            if r.levelno >= logging.WARNING and r.name.startswith("engine"):
                logs.append(r.getMessage())

    h = Catch()
    root = logging.getLogger()
    root.addHandler(h)
    try:
        world, _ = build_game(name, install, seed=1)
        sim = Simulation(world, triggers=True)
        for _ in range(ticks):
            sim.step([])
        s = world.script
        return {"crash": "", "result": triggers.result(world) or "", "tick": world.tick,
                "unsupported": sorted("%s:%d" % k for k in s.unsupported), "unbuilt": sorted("%s:%d" % k for k in s.unbuilt),
                "casts": sorted(world.unbuilt_casts), "errors": list(s.errors), "unknown_units": len(world.report.unknown_units),
                "warnings": sorted(set(logs))}
    except Exception as e:                  # a crash is a coverage result, not a tool failure
        return {"crash": "%s: %s" % (type(e).__name__, e), "result": "", "tick": 0, "unsupported": [], "unbuilt": [], "casts": [], "errors": [],
                "unknown_units": 0, "warnings": []}
    finally:
        root.removeHandler(h)


# --- the report -----------------------------------------------------------------------------------------------------------------------------------

def collect(install, ticks=SMOKE_TICKS, only=None):
    """Scan and smoke every campaign map.  Returns `(rows, features)`: one row per map (dict) and the `Feature` table that covers them."""
    from allods2.assets import AssetCache
    from allods2.cli import campaign_maps, open_map
    from engine.session import build_game
    assets = AssetCache(install)
    rows, feats = [], dict(FEATURES)
    for path in campaign_maps(install):
        name = os.path.basename(path).rsplit(".", 1)[0]
        if only and name not in only:
            continue
        m = open_map(path, install)
        world, _ = build_game(name, install, seed=1)
        counts = scan(world, m, assets)
        for fid in counts:
            if fid not in feats and fid.split(".")[0] in ("check", "instant", "group"):
                feats[fid] = script_feature(*_split(fid))
            elif fid.startswith("spell.") and fid not in feats:
                feats[fid] = _spell_feature(assets, int(fid[6:]))
            elif fid in ("varref", "unitname"):
                feats[fid] = Feature(fid, "variable reference 8000-9999" if fid == "varref" else "unit by name >= 11001", MISSING, BLOCKER, "",
                                     "never written by the exe (triggers.md 2.3)")
        h = m.header
        rows.append({"map": name, "title": h.name, "size": "%dx%d" % (h.width, h.height), "players": h.player_count, "units": len(m.units),
                     "counts": counts, "smoke": smoke(name, install, ticks)})
    return rows, feats


def _split(fid):
    what, n = fid.split(".")
    return what, int(n)


def _spell_feature(assets, n):
    try:
        name = assets.spells().get(n).name
    except Exception:
        name = "spell %d" % n
    return Feature("spell.%d" % n, "spell %d %s" % (n, name), BUILT, POLISH, "", "")


def blockers(row, feats):
    """The features that keep the map from being completed as designed: not built, impact BLOCKER, present on the map."""
    out = [fid for fid, c in row["counts"].items() if c and fid in feats and feats[fid].status != BUILT and feats[fid].impact == BLOCKER]
    if row["smoke"]["crash"]:
        out.append("crash")
    return sorted(out)


def gaps(row, feats):
    return sorted(fid for fid, c in row["counts"].items()
                  if c and fid in feats and feats[fid].status != BUILT and feats[fid].impact != BLOCKER)


def verdict(row, feats):
    """`blocked`, `playable, gameplay gaps` (a usable structure the engine ignores, a spell duration) or `playable now` (polish gaps only: no sound,
    arrows and status effects not drawn)."""
    if blockers(row, feats):
        return "blocked"
    return "playable, gameplay gaps" if any(feats[g].impact == GAMEPLAY for g in gaps(row, feats)) else "playable now"


def steps_of(fids, feats):
    return {feats[f].step for f in fids if f in feats and feats[f].step}


def proposed_order(rows, feats):
    """The order of the steps, by what the map data says.  First the steps that unblock maps: greedy, the next one completes the most blocker lists
    per unit of effort (ties: maps touched, then the smaller effort).  Then the steps whose features the maps contain, gameplay before polish, by
    maps touched per unit of effort.  Last the global steps (no map data asks for them), cheapest first.  Returns `[(step id, newly playable maps,
    maps touched)]`."""
    need = {r["map"]: {feats[f].step for f in blockers(r, feats) if f in feats and feats[f].step} for r in rows}
    touched, worst = defaultdict(set), {}
    rank = {GAMEPLAY: 1, POLISH: 2}
    for r in rows:
        for f, c in r["counts"].items():
            if c and f in feats and feats[f].status != BUILT and feats[f].step:
                st = feats[f].step
                touched[st].add(r["map"])
                worst[st] = min(worst.get(st, 3), 0 if feats[f].impact == BLOCKER else rank[feats[f].impact])
    for st in STEPS.values():
        if st.glob:
            touched[st.id] = touched[st.id] | {r["map"] for r in rows}
            worst.setdefault(st.id, 3)
    done, order, free = set(), [], {m for m, s in need.items() if not s}

    def gain(st):
        return {m for m, n in need.items() if m not in free and n and n <= done | {st}}

    left = [st for st in STEPS if touched[st]]
    while left:
        best = max(left, key=lambda st: (len(gain(st)) / STEPS[st].effort, -worst.get(st, 3) if not gain(st) else 1, len(touched[st]) / STEPS[st].effort))
        if not gain(best):
            best = min((st for st in left), key=lambda st: (worst.get(st, 3), -len(touched[st]) / STEPS[st].effort, STEPS[st].effort))
        g = gain(best)
        free |= g
        done.add(best)
        left.remove(best)
        order.append((best, sorted(g), sorted(touched[best])))
    return order


def write_csv(path, rows, feats):
    fids = sorted(feats, key=lambda f: (f.split(".")[0], int(f.split(".")[1]) if f.split(".")[-1].isdigit() else 0, f))
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["map", "title", "size", "players", "units", "verdict", "blockers", "smoke_result", "smoke_crash", "smoke_unbuilt"] + fids)
        w.writerow(["status", "", "", "", "", "", "", "", "", ""] + [feats[f].status + "/" + feats[f].impact for f in fids])
        for r in rows:
            s = r["smoke"]
            w.writerow([r["map"], r["title"], r["size"], r["players"], r["units"], verdict(r, feats), " ".join(blockers(r, feats)), s["result"], s["crash"],
                        " ".join(s["unbuilt"] + s["unsupported"] + ["cast:%d" % c for c in s["casts"]])] + [r["counts"].get(f, 0) or "" for f in fids])
    return path


def _kind_name(fid):
    from engine.sim import triggers as T
    what, n = fid.split(".")
    return T._NAMES[what].get(int(n), "unnamed")


def _tidy(items, key=lambda x: x):
    return ", ".join(str(key(i)) for i in items)


def render(rows, feats):
    """The generated block of docs/coverage.md."""
    n = len(rows)
    ver = {r["map"]: verdict(r, feats) for r in rows}
    tiers = Counter(ver.values())
    ok = tiers["playable now"] + tiers["playable, gameplay gaps"]
    L = ["Scanned %d campaign maps; smoke run %d ticks of the map script and the AI with no player." % (n, rows[0]["smoke"]["tick"] if rows else 0), "",
         "**%d of %d maps have no known blocker** (%d playable now, %d with gameplay gaps), %d are blocked. This is an upper bound: it means no feature "
         "in the list below stops the mission and the smoke run did not crash, not that the map has been played." % (ok, n, tiers["playable now"],
                                                                                                                   tiers["playable, gameplay gaps"], tiers["blocked"]),
         "", "- **blocker**: the mission cannot be completed as designed (a script variable that gates the goal is fed by an action the engine cannot do).",
         "- **gameplay gap**: content the engine ignores but the goal does not depend on (a usable well, a spell duration).",
         "- **polish**: simulated but not drawn or played (arrows, status effects, music).", "",
         "### Per map", "", "| Map | Name | Verdict | Blockers | Gameplay gaps | Smoke |", "|---|---|---|---|---|---|"]
    for r in rows:
        g = [x for x in gaps(r, feats) if feats[x].impact == GAMEPLAY]
        sm = r["smoke"]
        L.append("| %s | %s | %s | %s | %s | %s |" % (r["map"], r["title"] or "", ver[r["map"]], ", ".join(blockers(r, feats)),
                                                      ", ".join("%s x%d" % (x, r["counts"][x]) for x in g), "crash" if sm["crash"] else (sm["result"] or "ok")))
    L += ["", "### Per feature the engine does not fully have", "",
          "`Unblocks alone` = maps whose only blocker it is. Every map has `music.zones`, so polish features touch nearly all maps.", "",
          "| Feature | What | Status | Impact | Step | Maps | Unblocks alone | Note |", "|---|---|---|---|---|---|---|---|"]
    for fid in sorted(f for f in feats if feats[f].status != BUILT):
        f = feats[fid]
        on = [r["map"] for r in rows if r["counts"].get(fid)]
        alone = [r["map"] for r in rows if blockers(r, feats) == [fid]]
        L.append("| `%s` | %s | %s | %s | %s | %d | %s | %s |" % (fid, f.title, f.status, f.impact, f.step or "-", len(on), len(alone) if f.impact == BLOCKER else "-", f.note))
    L += ["", "### Script kinds the maps use (reachable from an active trigger)", "",
          "Variable references 8000-9999 and unit names >= 11001 are used by no map. Status comes from the trigger code (`trigger_status`).", "",
          "| Kind | Editor name | Maps | Status |", "|---|---|---|---|"]
    for fid in sorted((f for f in feats if f.split(".")[0] in ("check", "instant", "group")), key=_kind_sort):
        on = [r["map"] for r in rows if r["counts"].get(fid)]
        if on:
            L.append("| `%s` | %s | %d | %s |" % (fid, _kind_name(fid), len(on), feats[fid].status))
    spells = sorted((f for f in feats if f.startswith("spell.") and f[6:].isdigit()), key=lambda f: int(f[6:]))
    L += ["", "### Spells found on units and items", "",
          "From unit spell slots and books, and from `castSpell` / `teachSpell` on carried items, sacks and unit equipment. Every one has a built handler "
          "([spells §9d](data/spells.md)); what is not drawn is `spell.status`.", "", "| Spell | Maps | Sources |", "|---|---|---|"]
    for fid in spells:
        on = [r for r in rows if r["counts"].get(fid)]
        L.append("| %s | %d | %d |" % (feats[fid].title[len("spell "):], len(on), sum(r["counts"][fid] for r in on)))
    cls = [("unit.caster", "casters (book or special-attack slot)"), ("unit.ranged", "shooters"), ("unit.flyer", "flyers"), ("unit.ghost", "ghosts and bees")]
    L += ["", "### Unit classes (non-player units at map start)", "", "| Class | Units | Maps | Engine |", "|---|---|---|---|"]
    for fid, label in cls:
        L.append("| %s | %d | %d | %s |" % (label, sum(r["counts"].get(fid, 0) for r in rows), sum(1 for r in rows if r["counts"].get(fid)), feats[fid].note or feats[fid].status))
    L += ["", "### Global gaps (not tied to a map's data)", "",
          "Steps the maps do not need to be completed but a finished game does; each touches every map.", "",
          "| Step | Effort | Backlog item |", "|---|---|---|"]
    for st in STEPS.values():
        if st.glob:
            L.append("| `%s` %s | %d | %s |" % (st.id, st.title, st.effort, st.backlog or "-"))
    odd = [(r["map"], r["smoke"]["result"]) for r in rows if r["smoke"]["result"]]
    crashes = [(r["map"], r["smoke"]["crash"]) for r in rows if r["smoke"]["crash"]]
    L += ["", "### Smoke observations", ""]
    unsup = sorted({k for r in rows for k in r["smoke"]["unsupported"]})
    unbuilt = sorted({k for r in rows for k in r["smoke"]["unbuilt"]})
    L += ["- crash on map %s: `%s`" % c for c in crashes] or ["- no crashes."]
    L += ["- script kinds the engine does not know (`not implemented`): %s." % (_tidy(unsup) if unsup else "none"),
          "- script no-ops the engine counted (`Script.unbuilt`): %s; unbuilt spell releases: %s." % (
              _tidy(unbuilt) if unbuilt else "none", _tidy(sorted({c for r in rows for c in r["smoke"]["casts"]})) or "none")]
    L += ["- the idle party (nothing ordered) is **lost** within %d ticks on maps %s: a fresh level-1 party standing still; not checked against the original, "
          "not a blocker." % (rows[0]["smoke"]["tick"] if rows else 0, _tidy([m for m, v in odd if v == "lost"]))] if odd else []
    L += ["", "### Proposed step order", "",
          "First the steps that unblock maps (greedy: the next one completes the most blocker lists per unit of effort), then the steps whose features "
          "the maps contain (gameplay before polish, by maps touched per unit of effort), last the global steps no map data asks for (cheapest first). "
          "Effort is the author's estimate in relative units (`STEPS` in `engine/coverage.py`: 1 = a small spec-and-build step like J3).", "",
          "| # | Step | Effort | Maps newly playable | Playable after | Maps touched | Backlog item |", "|---|---|---|---|---|---|---|"]
    total = ok
    for i, (sid, gain, touched) in enumerate(proposed_order(rows, feats), 1):
        st = STEPS[sid]
        total += len(gain)
        L.append("| %d | `%s` %s | %d | %s | %d | %d | %s |" % (i, sid, st.title, st.effort, "%d (%s)" % (len(gain), _tidy(gain)) if gain else "-", total, len(touched), st.backlog or "-"))
    return "\n".join(L) + "\n"


def _kind_sort(fid):
    what, n = fid.split(".")
    return ("check", "instant", "group").index(what), int(n)


def write_docs(path, block):
    """Replace the generated block of `path` (created with a header when missing)."""
    text = open(path, encoding="utf-8").read() if os.path.exists(path) else "# Map coverage\n\n%s\n%s\n" % (BEGIN, END)
    if BEGIN not in text or END not in text:
        text = text.rstrip() + "\n\n%s\n%s\n" % (BEGIN, END)
    head, rest = text.split(BEGIN, 1)
    tail = rest.split(END, 1)[1]
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(head + BEGIN + "\n\n" + block + "\n" + END + tail)
    return path


def summary(rows, feats):
    """One line for a K step's close-out."""
    ver = Counter(verdict(r, feats) for r in rows)
    return "coverage: %d of %d maps without a blocker (%d playable now, %d with gameplay gaps), %d blocked" % (
        len(rows) - ver["blocked"], len(rows), ver["playable now"], ver["playable, gameplay gaps"], ver["blocked"])


def run(install, ticks=SMOKE_TICKS, csv_path=None, docs_path=None, only=None, out=print):
    from allods2.common import OUT
    rows, feats = collect(install, ticks, only)
    csv_path = csv_path or os.path.join(str(OUT), "coverage.csv")
    out("wrote " + write_csv(csv_path, rows, feats))
    if docs_path:
        out("wrote " + write_docs(docs_path, render(rows, feats)))
    out(summary(rows, feats))
    return rows, feats
